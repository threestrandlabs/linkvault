export const domainOf = (u: string): string => {
  if (!u) return '';
  const clean = String(u).trim().replace(/^https?:\/\//i, '').replace(/^www\./i, '');
  const host = clean.split('/')[0].split('?')[0].split('#')[0];
  return host || '';
};
